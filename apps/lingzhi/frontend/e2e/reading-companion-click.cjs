// Real local source fixture. No production course or student data is used.
// Set BASE_URL, SESSION_FILE, ARTIFACT_DIR and PLAYWRIGHT_MODULE for an isolated run.
const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright')
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict')
;(async()=>{
 const browser=await chromium.launch({channel:'msedge',headless:true})
 try {
  const context=await browser.newContext({viewport:{width:1440,height:1000}})
  const page=await context.newPage()
  await page.goto(process.env.BASE_URL)
  await page.evaluate(({token,user})=>{sessionStorage.setItem('lingzhi_student_session_v1',token);sessionStorage.setItem('lingzhi_student_identity_v1',JSON.stringify(user))},JSON.parse(fs.readFileSync(process.env.SESSION_FILE,'utf8')))
  await page.evaluate(locale=>localStorage.setItem('app-locale',locale),process.env.LOCALE||'zh')
  await page.goto(process.env.BASE_URL+'/course/pilot-course/learn/pilot-n')
  const paragraph=page.locator('.course-content-block p').first();await paragraph.waitFor();await page.waitForTimeout(1200)
  await paragraph.evaluate(el=>{const range=document.createRange();const walker=document.createTreeWalker(el,NodeFilter.SHOW_TEXT);let text;while(text=walker.nextNode()){if(text.textContent.trim().length>8)break}range.setStart(text,0);range.setEnd(text,8);const selection=getSelection();selection.removeAllRanges();selection.addRange(range);el.dispatchEvent(new MouseEvent('mouseup',{bubbles:true}))})
  await page.locator('#selection-menu').waitFor();await page.waitForTimeout(300)
  assert.equal(await page.locator('.reading-companion-surface.is-inline:visible').count(),0,'Selecting text must not open the companion')
  console.log('Selection leaves the companion closed: passed')
  await page.locator('#selection-menu button').first().click()
  const inline=page.locator('.reading-companion-surface.is-inline:visible')
  await inline.locator('.study-dialogue.is-compact').waitFor()
  assert.equal(await inline.locator('.study-tabs,.study-teaching-actions,.study-source').count(),0)
  if(!await inline.locator('textarea').count())await inline.locator('.inline-reply-actions button').first().click()
  await inline.locator('textarea').fill('用两句话解释内层与外层，不要展开全部求导过程。')
  const completed=page.waitForResponse(r=>r.url().endsWith('/command')&&r.request().method()==='POST'&&r.request().postDataJSON()?.action==='discuss',{timeout:120000})
  await inline.locator('form').evaluate(el=>el.dispatchEvent(new Event('submit',{bubbles:true,cancelable:true})))
  const response=await completed;assert.equal(response.status(),200);const saved=await response.json()
  await inline.locator('.study-message.assistant').last().waitFor({timeout:120000})
  await page.waitForTimeout(200)
  assert.equal(await inline.locator('.reading-companion-toolbar,.reading-companion-more,.study-composer').count(),0,'A short answer adds no workspace chrome or permanently open composer')
  const body=inline.locator('.study-body')
  const geometry=await body.evaluate(el=>({client:el.clientHeight,scroll:el.scrollHeight}))
  assert(geometry.client>=geometry.scroll-2,'Inline answer must not be hidden inside a cramped scroll area')
  const output=process.env.ARTIFACT_DIR||'.';fs.mkdirSync(output,{recursive:true})
  await inline.scrollIntoViewIfNeeded();await page.screenshot({path:path.join(output,`companion-click-${process.env.LOCALE||'zh'}.png`),fullPage:true})
  console.log('Explicit click and original-menu-only short answer: passed')
  // Deterministic UI-only long-reply case, not model evidence.
  await page.route('**/study-dialogues/*/command',async route=>{
    const data=JSON.parse(JSON.stringify(saved))
    const conversation=data.conversation||data
    const answer=conversation.messages.findLast(m=>m.role==='assistant')
    answer.content='合成长解释段落。'.repeat(120)
    await route.fulfill({status:200,contentType:'application/json',body:JSON.stringify(data)})
  })
  await inline.locator('.inline-reply-actions button').first().click()
  await inline.locator('textarea').fill('合成长回复界面检查')
  await inline.locator('form').evaluate(el=>el.dispatchEvent(new Event('submit',{bubbles:true,cancelable:true})))
  await inline.getByTestId('companion-expand').waitFor()
  await inline.locator('.inline-reply-actions button').first().click()
  await inline.locator('textarea').fill('保留这个未发送追问')
  await inline.getByTestId('companion-expand').click()
  assert.equal(await page.locator('.study-composer textarea').inputValue(),'保留这个未发送追问')
  await page.getByTestId('companion-return-inline').click()
  assert.equal(await inline.locator('textarea').inputValue(),'保留这个未发送追问')
  console.log('Synthetic long reply offers original companion and preserves the draft: passed')
 } finally {await browser.close()}
})().catch(e=>{console.error(e);process.exitCode=1})
